/**
 * 决策复盘的字段释义。
 *
 * 为什么单独放一个文件而不是写成 tooltip：这些数字全都是「事后才知道」的推导值，
 * 页面上没有一个数的含义是望文能生义的——「平均前瞻 -0.72%」到底是在夸谁、
 * 「挑增 -2.98pp」是模型的锅还是我的锅，不看定义铁定读反。
 * tooltip 装不下这么多因果，所以给一整屏，按三层分组，随时能对照。
 */

import type { FundEvaluation } from '../types';

interface Entry {
  term: string;
  desc: string;
  /** 一眼能看懂的实例 */
  eg?: string;
}

function Group({ title, note, entries }: { title: string; note?: string; entries: Entry[] }) {
  return (
    <details className="gloss-group" open>
      <summary className="gloss-summary">
        <span className="gloss-title">{title}</span>
        <span className="faint">{entries.length} 项</span>
      </summary>
      {note ? <p className="gloss-note">{note}</p> : null}
      <dl className="gloss-list">
        {entries.map((e) => (
          <div className="gloss-item" key={e.term}>
            <dt className="mono">{e.term}</dt>
            <dd>
              {e.desc}
              {e.eg ? <span className="gloss-eg">{e.eg}</span> : null}
            </dd>
          </div>
        ))}
      </dl>
    </details>
  );
}

